#!/bin/bash

# 에러 발생 시 즉시 스크립트 실행을 중단합니다.
set -e

echo "=================================================="
echo "🚀 AWS 운영 서버 배포를 시작합니다..."
echo "=================================================="

# 1. 최신 소스코드 원격(GitHub)에서 가져오기
echo "📥 깃허브에서 최신 소스코드를 가져옵니다 (git pull)..."
git pull origin main


# 3. 도커 서비스 중지 및 재빌드 실행
echo "🐳 도커 컨테이너 재빌드 및 백그라운드 실행을 시작합니다..."
docker compose down
docker compose up -d --build

# 4. 안 쓰는 빌드 이미지 정리 (용량 부족 방지)
echo "🧹 미사용 도커 리소스를 정리합니다 (prune)..."
docker image prune -f

echo "=================================================="
echo "✅ 배포 작업이 성공적으로 완료되었습니다!"
echo "=================================================="
